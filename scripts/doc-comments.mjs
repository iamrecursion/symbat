// The three comment shapes this repository uses, and the check that stops them drifting apart
// again.
//
// A comment's shape follows from what it *is* rather than from how long it is. A module header is
// `//` lines at the top of a file, because it is prose about a module and not documentation of a
// declaration — give it `/**` and it attaches to whatever import happens to follow. A doc comment
// that fits on one line is `/** … */`. One that does not is canonical JSDoc: `/**` alone, ` * `
// continuations, `*/` alone, which is the form every editor, `tsc`'s quick-info and every future
// tool already assume.
//
// A script rather than a paragraph in CONTRIBUTING, because a written convention is what the two
// styles this replaced grew up under: 834 blocks hung their continuations under text on the opener
// and 717 were canonical, with both shapes inside single files. Nothing else in the toolchain can
// hold the line — dprint's TypeScript plugin treats a comment's text as opaque, and there is no
// eslint-plugin-jsdoc here.
//
// It re-delimits and nothing else. Where a line breaks inside a paragraph is a judgment somebody
// made, so prose, `_italics_`, `{@link}` and the relative indent of a bullet's continuation all
// pass through untouched; the rewrite moves text between the delimiter columns and preserves the
// spacing between lines. That is what makes `--fix` reviewable as "no line says anything
// different", and it is why the whole conversion could be checked against a byte-identical
// `main.js`.
//
// Comments are found with TypeScript's own parser rather than by matching `^\s*\*`, which finds
// multiplication inside a fenced sample and `/*` inside a string literal or a regex.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

// Where the plugin's own code lives, plus the build scripts at the root. `src/wasm` is generated by
// wasm-bindgen and is ignored here for the same reason ESLint ignores it.
const ROOTS = ["src", "test", "scripts"];
const SKIP = ["src/wasm"];

/** Every file this convention covers, in a stable order so two runs report the same list. */
function sourceFiles() {
  const found = [];

  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = `${dir}/${entry.name}`;
      if (SKIP.includes(path)) {
        continue;
      }
      if (entry.isDirectory()) {
        walk(path);
      } else if (/\.(ts|mjs)$/.test(entry.name)) {
        found.push(path);
      }
    }
  };

  for (const root of ROOTS) {
    walk(root);
  }
  for (const entry of readdirSync(".", { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith(".mjs")) {
      found.push(entry.name);
    }
  }

  return found.sort();
}

/**
 * Every comment in a file, in source order.
 *
 * Comments are trivia, so they hang off the token that follows them rather than appearing in the
 * tree; walking to the tokens and asking for the trivia on each is what reaches all of them,
 * including whatever precedes the end-of-file token. A comment that both trails one token and
 * leads the next is seen twice, hence the map.
 */
function comments(text, path) {
  const kind = path.endsWith(".mjs") ? ts.ScriptKind.JS : ts.ScriptKind.TS;
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, kind);
  const found = new Map();

  const visit = (node) => {
    for (const child of node.getChildren(source)) {
      if (child.getChildCount(source) > 0) {
        visit(child);
        continue;
      }
      for (const range of ts.getLeadingCommentRanges(text, child.getFullStart()) ?? []) {
        found.set(range.pos, range);
      }
      for (const range of ts.getTrailingCommentRanges(text, child.getEnd()) ?? []) {
        found.set(range.pos, range);
      }
    }
  };

  visit(source);
  return [...found.values()].sort((a, b) => a.pos - b.pos);
}

/** The whitespace between the start of `pos`'s line and `pos`, or `null` if code precedes it. */
function ownLineIndent(text, pos) {
  const indent = text.slice(text.lastIndexOf("\n", pos - 1) + 1, pos);
  return /^[ \t]*$/.test(indent) ? indent : null;
}

/**
 * The comment as the convention would write it, or `null` for a shape this script will not guess
 * at.
 *
 * Content is carried by absolute column rather than by stripping a fixed prefix, so a block whose
 * continuations hang under text on the opener and one that is already canonical are read the same
 * way: take each line's text and the column it starts at, then re-lay the whole block against ` * `
 * with every column shifted by the same amount. Relative indent — a bullet's continuation, a
 * fenced sample — survives because only the leftmost column is pinned.
 *
 * Text on the opener is the exception, and is pinned to the leftmost column rather than measured.
 * Its column says where `/** ` ends and nothing about the author's intent, so measuring it turns
 * the sixteen blocks that hang their continuations at ` * ` while their first line sits at `/** `
 * into blocks whose first line is indented by one.
 */
function canonical(raw, indent) {
  if (indent.includes("\t")) {
    return null;
  }

  if (!raw.includes("\n")) {
    return `/** ${raw.slice(3, -2).trim()} */`;
  }

  const lines = raw.split("\n");
  const content = [];
  let openerText = null;

  const opener = lines[0].slice(3);
  if (opener.trim() !== "") {
    openerText = { column: indent.length + 3, text: opener.trim() };
    content.push(openerText);
  }

  for (let i = 1; i < lines.length; i++) {
    const last = i === lines.length - 1;
    const line = last ? lines[i].slice(0, -2) : lines[i];
    const star = /^[ \t]*\*/.exec(line);

    if (star === null) {
      // The only line inside a doc comment that may carry no `*` is the one holding a lone `*/`.
      if (last && line.trim() === "") {
        continue;
      }
      return null;
    }

    const rest = line.slice(star[0].length);
    if (rest.trim() === "") {
      content.push(null);
    } else {
      content.push({ column: star[0].length + /^ */.exec(rest)[0].length, text: rest.trim() });
    }
  }

  const columns = content.filter((line) => line !== null && line !== openerText).map((line) => line.column);
  if (columns.length === 0 && openerText === null) {
    return null;
  }

  const leftmost = columns.length > 0 ? Math.min(...columns) : openerText.column;
  if (openerText !== null) {
    openerText.column = leftmost;
  }
  const body = content.map((line) =>
    line === null ? `${indent} *` : `${indent} * ${" ".repeat(line.column - leftmost)}${line.text}`
  );

  // The range starts at `/**`, so the first line carries no indent of its own.
  return ["/**", ...body, `${indent} */`].join("\n");
}

/** What the report says about each way a comment can be wrong. Only `shape` is one `--fix` mends. */
const RULES = {
  shape: "not the shape the convention gives it: `/** … */` when it fits on one line, and `/**`\n"
    + "    alone, ` * ` continuations and `*/` alone when it does not",
  block: "a block comment that is not a doc comment; a module header or an aside is `//` lines",
  header: "a file opens with a block comment; a module header is `//` lines, so that it documents\n"
    + "    the module rather than attaching to the first import",
  placement: "a doc comment that spans lines shares its line with code, which leaves it no indent\n"
    + "    of its own to be laid out against; give it a line to itself",
  adjacent: "a doc comment sits directly against the one above it, with no declaration between;\n"
    + "    one of the two has almost certainly landed above the wrong thing",
  unknown: "a multi-line doc comment in a shape this check will not rewrite by guessing",
};

const findings = [];
const fix = process.argv.includes("--fix");
let fixed = 0;
let total = 0;

for (const path of sourceFiles()) {
  const text = readFileSync(path, "utf8");
  const found = comments(text, path);
  const edits = [];
  let previous = null;

  const preamble = /^\s*/.exec(text)[0].length;
  const at = (pos) => text.slice(0, pos).split("\n").length;
  const report = (pos, rule) => findings.push({ path, line: at(pos), rule });

  for (const range of found) {
    const raw = text.slice(range.pos, range.end);
    const documentation = raw.startsWith("/**");
    const indent = ownLineIndent(text, range.pos);

    if (range.kind === ts.SyntaxKind.SingleLineCommentTrivia) {
      previous = range;
      continue;
    }

    total++;

    if (!documentation) {
      report(range.pos, "block");
    } else if (range.pos === preamble) {
      report(range.pos, "header");
    } else if (indent === null && raw.includes("\n")) {
      report(range.pos, "placement");
    } else {
      // A one-liner needs no indent, and inline is a fair place for one: `f(/** the count */ 3)`.
      const want = canonical(raw, indent ?? "");
      if (want === null) {
        report(range.pos, "unknown");
      } else if (want !== raw) {
        report(range.pos, "shape");
        edits.push({ range, want });
      }
    }

    // The back-to-back scan, which is here rather than in review because the insert that causes it
    // — one anchored on `export function` — lands the new doc under the previous declaration's doc,
    // where it reads as if it belonged there. Nothing but a single newline may separate the two for
    // this to be what happened: code on either line means they document different things.
    const between = previous === null ? null : text.slice(previous.end, range.pos);
    if (
      documentation && indent !== null && between !== null
      && previous.kind === ts.SyntaxKind.MultiLineCommentTrivia
      && between.trim() === "" && between.split("\n").length === 2
    ) {
      report(range.pos, "adjacent");
    }

    previous = range;
  }

  if (fix && edits.length > 0) {
    let updated = text;
    for (const edit of edits.reverse()) {
      updated = updated.slice(0, edit.range.pos) + edit.want + updated.slice(edit.range.end);
    }
    writeFileSync(path, updated);
    fixed += edits.length;
  }
}

const unfixable = findings.filter((finding) => finding.rule !== "shape");

if (fix) {
  console.log(`Rewrote ${fixed} doc comment${fixed === 1 ? "" : "s"}.`);
}

if (findings.length === unfixable.length && unfixable.length === 0) {
  console.log(`All ${total} doc comments are in the three shapes CONTRIBUTING describes.`);
  process.exit(0);
}

for (const finding of fix ? unfixable : findings) {
  console.error(`${finding.path}:${finding.line}\n    ${RULES[finding.rule]}`);
}

if (!fix && findings.length > unfixable.length) {
  console.error("\nRun `make docstyle-fix` to rewrite the ones that are only mis-delimited.");
}

process.exit(fix && unfixable.length === 0 ? 0 : 1);
